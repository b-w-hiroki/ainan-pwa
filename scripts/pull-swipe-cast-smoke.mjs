import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { PULL_CAST_TUNING, classifyPullRelease, pullChargeRatio, slingshotAimFromPull } from '../fishing-game/js/game/pullCastTuning.js'

const read = path => readFileSync(new URL('../' + path, import.meta.url), 'utf8')
const input = read('fishing-game/js/game/installConeCastRetrievePrototype.js')
const motion = read('fishing-game/js/game/installCastCameraPanPrototype.js')

assert.deepEqual(PULL_CAST_TUNING.gauge, { fillMs: 900, successStart: 0.62, successEnd: 0.82, lateThreshold: 1 })
assert.equal(PULL_CAST_TUNING.gesture.minPullDistancePx, 64)
assert.equal(PULL_CAST_TUNING.gesture.originRadiusPx, 62)
assert.equal(PULL_CAST_TUNING.error.successMaxLandingErrorPx, 8)
assert.deepEqual(PULL_CAST_TUNING.motion, { chargePoseBlendEnd: 0.18, cameraDelayAfterLureMs: 36, lureDetachBlendMs: 48, recoveryMs: 90 })

const leftPull = slingshotAimFromPull(-64, 80)
const rightPull = slingshotAimFromPull(64, 80)
const shortPull = slingshotAimFromPull(-12, 18)
const fullPull = slingshotAimFromPull(-80, 120)
const upwardPull = slingshotAimFromPull(-48, -80)
assert.ok(leftPull.directionOk && rightPull.directionOk, 'both down-left and down-right diagonals must be valid')
assert.ok(leftPull.angleDeg > 0 && rightPull.angleDeg < 0, 'cast direction must be inverse to horizontal pull')
assert.ok(Math.abs(leftPull.angleDeg + rightPull.angleDeg) < 0.001, 'symmetric pulls must produce symmetric cast angles')
assert.ok(fullPull.distancePx > shortPull.distancePx, 'longer pull must request longer flight')
assert.equal(fullPull.pullProgress, 1, 'pull length must clamp at full range')
assert.equal(upwardPull.directionOk, false, 'upward drags must not arm a cast')

assert.equal(classifyPullRelease(0.2, -1).rating, 'early')
assert.equal(classifyPullRelease(0.72, 1).rating, 'good')
assert.equal(classifyPullRelease(0.95, 1).rating, 'late')
assert.equal(classifyPullRelease(0.72, 1).distanceScale, 1)
assert.equal(classifyPullRelease(0.72, 1).angleOffsetDeg, 0)
assert.equal(pullChargeRatio(450), 0.5)
assert.equal(pullChargeRatio(1200), 1)

assert.match(input, /inSlingshotOrigin\(this, pointer\)/, 'cast drag must start at the character origin')
assert.doesNotMatch(input, /setAimFromWorld/, 'water-surface aim drag must not remain')
assert.match(input, /inputMode === 'pull'/)
assert.match(input, /pullPointerId/)
assert.match(input, /pointerupoutside/)
assert.match(input, /pointercancel/)
assert.match(input, /abilityLimited/)
assert.match(input, /adjustedPower/)
assert.match(input, /classifyPullRelease\(0\.72/, 'keyboard alternative must use the success path')
assert.ok(input.includes('起点を左下へ引く'), 'concise Japanese slingshot guidance missing')
assert.ok(input.includes('反対へ'), 'inverse-direction feedback missing')
assert.match(input, /strokePoints\(selection\.points, false\)/, 'the actual lure trajectory must own the primary cast line')
assert.match(input, /x: raw\.x, y: raw\.y, clampedX: raw\.x/, 'preview must report the actual landing point first')
assert.doesNotMatch(input, /lineBetween\(raw\.x, raw\.y, shownTarget\.x/, 'unreachable requested range must not dominate the cast line')
assert.match(input, /lineStyle\(4, 0xffd95a, 0\.98\)/, 'finger pull must use a distinct gold gesture tether')
assert.match(motion, /playPrechargedRelease/)
assert.match(motion, /source: 'pullRelease'/)
assert.match(motion, /function updatePullCastTimeline/)
assert.match(motion, /timeline\.originalFireCast\.apply\(scene, timeline\.args\)/)
assert.ok(motion.indexOf('timeline.originalFireCast.apply') < motion.indexOf('scene.fishingCamera?.beginCastPan', motion.indexOf('function updatePullCastTimeline')), 'lure release must precede camera pan')
assert.match(motion, /const activeAsset = t < 0\.5 \? fromAsset : toAsset/, 'pose changes must keep a single visible character')
assert.match(motion, /blend\.setAlpha\(0\)/, 'blend sprite must stay hidden')
assert.ok(!/localStorage|saveState|award|reward|score\s*[+]=|stamina\s*[+-]=/.test(input), 'pull UI must not mutate save/reward/stamina')

console.log('Slingshot cast smoke QA passed')
console.log('  inverse direction / pull range / origin-only start: OK')
console.log('  900ms timing / early-good-late / one-character pose: OK')
console.log('  range clamp / pointer ownership / cancel / keyboard / save isolation: OK')
