import assert from 'node:assert/strict'
import { existsSync, readFileSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { resolve } from 'node:path'

const file = p => readFileSync(new URL('../'+p,import.meta.url),'utf8')
const json = p => JSON.parse(file(p))
const contract=json('docs/pipeline/art-rebuild-v2-contract.json')
const current=json('docs/pipeline/art-direction-contract.json')
const golden=json('docs/pipeline/golden-screens.json')
const manifest=file('fishing-game/js/config/assetManifest.js')
const registry=json('docs/pipeline/visual-owners.json')
const canonical=file('docs/concept-art/canonical/README.md')
const resume=file('docs/AI-RESUME.md')
const pkg=json('package.json')

assert.equal(contract.schemaVersion,2)
assert.ok(contract.issue.endsWith('/217')&&contract.parent.endsWith('/216'))
assert.deepEqual(contract.viewport.portraitGolden,{width:390,height:844})
assert.deepEqual(contract.viewport.landscape.map(v=>v.width),[844,932])
assert.equal(contract.viewport.safeTouchMinCssPx,44)
assert.ok(contract.assetContract.requiredFields.includes('sha256'))
assert.ok(contract.assetContract.requiredFields.includes('rollbackAssetRef'))
assert.ok(contract.assetContract.promotionGates.some(s=>s.includes('human visual signoff')))
assert.equal(contract.acceptance.artisticApprovalAutomatic,false)
assert.equal(contract.acceptance.productionReplaced,false)
assert.ok(contract.assetContract.forbidden.some(s=>s.includes('Telea')))
assert.ok(contract.world.safeZone.includes('taut line'))
assert.ok(contract.player.pivots.includes('rodTip'))
assert.ok(contract.player.replaceable.includes('companion'))
assert.equal(contract.world.layers.length,10)
assert.equal(contract.world.layers.filter(x=>x.id==='hud')[0].owner,'W04')
assert.ok(contract.world.layers.every(x=>x.id&&x.alpha&&x.owner))
assert.ok(current.anchors.length>=8 && golden.frames.length>=16 && registry.slots.length>=6)
assert.match(canonical,/portrait and landscape smartphone/)
assert.doesNotMatch(canonical,/always a \*\*single portrait smartphone screen\*\*/i)
assert.match(canonical,/QA-only until.*visual.*production/i)
assert.match(resume,/issues\/216/)
assert.match(manifest,/fishingMotionCastRelease/)
assert.ok(pkg.scripts['qa:asset-rebuild'])
const out=resolve('artifacts/art-rebuild/w01-inventory.json')
execFileSync('node',['scripts/art/build-rebuild-inventory.mjs','artifacts/art-rebuild/w01-inventory.json'],{stdio:'inherit'})
assert.ok(existsSync(out))
const audit=JSON.parse(readFileSync(out,'utf8'))
assert.equal(audit.schemaVersion,1)
assert.ok(audit.summary.manifestEntries>70,'Inventory unexpectedly small')
assert.equal(audit.artApprovalInferred,false)
assert.equal(audit.productionSwitched,false)
assert.ok(audit.layoutRefs.every(a=>a.exists && /^[a-f0-9]{64}$/.test(a.sha256)))
assert.ok(audit.anchors.every(a=>a.exists && /^[a-f0-9]{64}$/.test(a.sha256)))
assert.ok(audit.qaOnly.every(a=>a.exists && a.manifested===false && a.artApproved===false))
assert.ok(audit.manifest.every(a=>a.id && a.textureKey && a.path))
assert.ok(audit.manifest.every(a=>a.sha256===null || /^[a-f0-9]{64}$/.test(a.sha256)))
assert.ok(audit.goldenScreenReferences.every(a=>a.sha256===null && a.hashVerified===false))
assert.equal(audit.summary.missingReady,0)
console.log('W01 source contract: real artifact hashes, no mistaken CI goldens, no unauthorized production promotion PASS')
